# Generates Eternit lane 14 (Passagen): the moulded five-channel wave block as an OBJ + the lane file.
import math, sys, os
from objgen import Mesh, sstep, cosramp, save_lane, lanes_dir, line

Z0, Z1 = 3.85, 5.00                      # the block (official: back end at 500 cm; norm drawing: about 1.2 m long)
BOUNDS = [-0.45, -0.265, -0.08, 0.08, 0.265, 0.45]     # channel edges: outer, high, centre (narrower), high, outer
# hills per channel: (start, crest, end, height). Outer and centre passages have two hills (norm side view, minigolfbau
# and Rothe photos); the Grenzlinie is behind the last one.
OUTER = [(3.90, 4.21, 4.48, 0.16), (4.50, 4.65, 4.92, 0.085)]
HIGH = [(3.85, 4.38, 4.92, 0.27)]
CENTRE = [(3.95, 4.24, 4.42, 0.043), (4.59, 4.68, 4.84, 0.04)]
WAVES = [OUTER, HIGH, CENTRE, HIGH, OUTER]
RW = 0.03                                # half width of a rib
RIB = 0.047                              # rib above the higher of the two channels next to it

def floor(i, z):
    best = 0.0
    for a, c, b, h in WAVES[i]:
        if a < z < b: best = max(best, h * (cosramp((z - a) / (c - a)) if z < c else cosramp((b - z) / (b - c))))
    return best

def rib_extra(z):
    return RIB * (0.4 + 0.6 * sstep((z - Z0) / 0.08)) * (0.25 + 0.75 * sstep((Z1 - z) / 0.18))

def height(x, z):
    if z <= Z0 or z >= Z1: return -0.004
    i = 0
    while i < 4 and x > BOUNDS[i + 1]: i += 1
    lo, hi = BOUNDS[i], BOUNDS[i + 1]; mid = (lo + hi) / 2; half = (hi - lo) / 2
    f = floor(i, z) + 0.012 * ((x - mid) / half) ** 2 * sstep((z - Z0) / 0.1) * sstep((Z1 - z) / 0.1)   # dished channel
    h = f
    for b, j in ((lo, i - 1), (hi, i + 1)):
        d = abs(x - b)
        if d < RW and 0 <= j <= 4:
            top = max(floor(i, z), floor(j, z)) + rib_extra(z)
            h = max(h, f + (top - f) * (1 + math.cos(math.pi * d / RW)) / 2)
    edge = sstep((z - Z0) / 0.03) * sstep((Z1 - z) / 0.03)
    return h * edge - 0.004 * (1 - edge)

M = Mesh()
xs = []
for i in range(5):
    lo, hi = BOUNDS[i], BOUNDS[i + 1]
    a = lo + (RW if i > 0 else 0); b = hi - (RW if i < 4 else 0)
    if i > 0: xs += [lo + RW * k / 6 for k in range(0, 6)]
    xs += [a + (b - a) * k / 8 for k in range(0, 8)]
    if i < 4: xs += [b + RW * k / 6 for k in range(0, 6)]
xs.append(0.45)
xs = [x * 0.452 / 0.45 for x in xs]
NZ = 110
rings = [[(x, height(x, Z0 + (Z1 - Z0) * j / NZ), Z0 + (Z1 - Z0) * j / NZ) for x in xs] for j in range(NZ + 1)]
M.skin(rings)
edge = rings[0] + [r[-1] for r in rings[1:]] + rings[-1][-2::-1] + [r[0] for r in rings[-2:0:-1]]
M.skin([[p, (p[0], -0.004, p[2])] for p in edge], 1, closed=True)

preview = len(sys.argv) > 1
M.write(sys.argv[1] if preview else os.path.join(lanes_dir(), 'eternit_14_passagen.obj'), 'Passagen - generated by tools/gen_passagen.py')
if not preview:
    parts = [{"name": "Passagen", "shape": "mesh", "file": "eternit_14_passagen.obj", "surface": True, "color": [0.12, 0.30, 0.75]}]
    for i in range(5):
        lo, hi = BOUNDS[i], BOUNDS[i + 1]; zc = WAVES[i][-1][1] + 0.035; w = (hi - lo) / 2 - RW
        parts.append(line("Grenzlinie_%d" % (i + 1), [round((lo + hi) / 2 - w, 3), zc], [round((lo + hi) / 2 + w, 3), zc], lift=round(floor(i, zc) + 0.004, 4)))
    lane = {"name": "Eternit 14 Passagen", "system": "Eternit", "length": 6.25, "width": 0.90, "targetCircle": 1.40,
            "tee": [0, 0.20], "cup": [0, 5.55], "parts": parts}
    save_lane(os.path.join(lanes_dir(), 'eternit_14_passagen.json'), """// Eternit lane 14 - Passagen.
// OFFICIAL (NormMiniatur 01/2026): back end of the obstacle 500 cm from the lane start; no fixed path; in every passage
//   the Grenzlinie is directly behind the crest of its (last) hill.
// MEASURED FROM THE NORM DRAWING (scaled): block about 1.15-1.2 m long; five passages, the centre one a little narrower;
//   Grenzlinien at about 442 cm (the two high passages), 468 (outer) and 470 (centre), so the crests are staggered.
// FROM PHOTOS (Rothe part, minigolfbau.eu - estimates): one moulded part; the passages are dished channels separated by
//   rounded ribs a few cm high (using 5-6 cm wide, about 4.5 cm above the higher neighbour) that follow the waves and
//   flatten out at both ends.
// FROM THE NORM SIDE VIEW AND PHOTOS: the outer passages have two hills (the first higher), the centre passage two very
//   low ones, the two high passages one large hill.
// ESTIMATES, low confidence: crest heights 27 cm (high passages; the schematic side view suggests 33, an Uppsala photo
//   24-30), 16 and 8.5 cm (outer), about 4 cm (centre). No measured value found.
// Generated by tools/gen_passagen.py - edit the generator, not this file.
""", lane)
