# Generates Eternit lane 7 (Sprungschanze mit Netz): the ramp and the net sock as OBJ files, and the lane file.
import math, sys, os
from objgen import Mesh, sstep, save_lane, lanes_dir

ZS, ZR, ZE = 1.13, 2.30, 2.50     # ramp start, ridge, foot of the back face (official: obstacle ends at 250 cm)
H = 0.50                          # ridge height (norm side view, scaled)
HC = 0.10                         # half width of the running channel (norm plan: about 21 cm wide)
ZRING, YRING, RRING = 5.05, 0.95, 0.25   # ring at the circle entrance; lower edge 70 cm above the tee level (70-80)

# ---------------------------------------------------------------- ramp
R = Mesh()
def ramp_ring(z):
    t = min(1.0, max(0.0, (z - ZS) / (ZR - ZS)))
    back = 1.0 if z <= ZR else max(0.0, 1 - (z - ZR) / (ZE - ZR))
    # the incline starts with a short rounded transition (12 cm) instead of a sharp kink - my assumption for a moulded
    # part; with a sharp kink the ball bounces off the foot of the ramp
    slope = H / (ZR - ZS); d = z - (ZS - 0.06)
    rise = slope * d * d / 0.24 if d < 0.12 else slope * (d - 0.06)
    f = min(rise, H) * back - 0.004 * (1 - sstep(d / 0.03))
    sh = 0.04 * t * back                       # shoulders above the channel floor
    W = 0.13 + 0.29 * t                        # half width of the base: 26 cm at the start, the lane width at the back
    half = [(0.0, f), (HC - 0.02, f), (HC - 0.008, f + 0.3 * sh), (HC + 0.004, f + 0.85 * sh), (HC + 0.015, f + sh),
            (HC + 0.03, f + sh - 0.004 * back * t), ((HC + 0.03 + W) / 2, (f + sh) / 2 - 0.002), (W, -0.004)]
    return [(-x, y, z) for x, y in reversed(half[1:])] + [(x, y, z) for x, y in half]
NZ = 90
R.skin([ramp_ring(ZS - 0.06 + (ZE - ZS + 0.06) * j / NZ) for j in range(NZ + 1)])

# ---------------------------------------------------------------- net sock (the ball collides with its inside)
S = Mesh()
def sock_ring(s):
    z = ZRING + 0.70 * s
    cy = YRING - 0.42 * s ** 1.5
    r = RRING * (1 - s) ** 0.8 + 0.02 * s
    return [(r * math.cos(a), cy + r * math.sin(a), z) for a in [2 * math.pi * k / 32 for k in range(33)]]
S.skin([sock_ring(j / 24) for j in range(25)])
tip = sock_ring(1.0)
S.skin([[(0.0, YRING - 0.42, ZRING + 0.70)] * 33, tip])

preview = len(sys.argv) > 1
if preview:
    R.write(sys.argv[1], 'ramp'); S.write(sys.argv[1].replace('.obj', '_sock.obj'), 'sock')
else:
    R.write(os.path.join(lanes_dir(), 'eternit_07_netz_ramp.obj'), 'Sprungschanze - generated by tools/gen_netz.py')
    S.write(os.path.join(lanes_dir(), 'eternit_07_netz_sock.obj'), 'net sock - generated by tools/gen_netz.py')
    ring = [[0.240, -0.010], [0.250, -0.012], [0.260, -0.010], [0.262, 0.0], [0.260, 0.010], [0.250, 0.012], [0.240, 0.010], [0.238, 0.0], [0.240, -0.010]]
    GREY = [0.55, 0.58, 0.60]
    lane = {"name": "Eternit 07 Netz", "system": "Eternit", "length": 6.25, "width": 0.90, "targetCircle": 1.40,
            "tee": [0, 0.20], "cup": [0, round(ZRING + 0.66, 3)], "cupHole": False, "cupHeight": round(YRING - 0.42, 3), "targetRadius": 0.22,
            "circleLine": False,
            "parts": [
                {"name": "Schanze", "shape": "mesh", "file": "eternit_07_netz_ramp.obj", "surface": True, "color": [0.92, 0.27, 0.12]},
                {"name": "Ring", "shape": "lathe", "axis": "z", "pos": [0, YRING, ZRING], "profile": ring, "material": "outer", "color": GREY},
                {"name": "Post", "shape": "box", "pos": [0, (YRING - RRING) / 2, ZRING], "size": [0.03, YRING - RRING, 0.03], "color": GREY},
                {"name": "Sock", "shape": "mesh", "file": "eternit_07_netz_sock.obj", "bounce": 0.05, "alpha": 0.35, "color": [0.95, 0.95, 0.92]},
                {"name": "SafetyNet", "shape": "arc", "center": [0, 5.55], "radius": 1.0, "from": 0, "to": 180, "height": 2.0, "thickness": 0.01,
                 "bounce": 0.05, "alpha": 0.30, "color": [0.20, 0.45, 0.35]}]}
    save_lane(os.path.join(lanes_dir(), 'eternit_07_netz.json'), """// Eternit lane 7 - Sprungschanze mit Netz (alternative 1: full lane).
// OFFICIAL (NormMiniatur 01/2026): the ramp ends 250 cm from the lane start; net ring 50 cm diameter, its lower edge
//   70-80 cm above the tee (using 70); target = inside of the net; no Grenzlinie.
// MEASURED FROM THE NORM DRAWING (scaled with the 250 cm dimension): ramp from 113 cm, straight incline (about 23
//   degrees) to the ridge at 230 cm, about 50 cm high, then a steep back face; a parallel running channel about 21 cm
//   wide up the middle; the base widens in straight lines from about 26 cm; the ring stands at the circle entrance;
//   the safety net is an arc behind the circle.
// STATED (minigolfbau.eu): safety net 200 cm high.
// FROM PHOTOS (minigolfbau.eu, Vorsfelde, Harrislee - estimates): the channel lies between two shoulders that are a few
//   cm higher at the top (using 4 cm); the net is a see-through sock that hangs down behind the ring (using 70 cm long).
//   Photos suggest a lower ramp (30-40 cm) than the norm side view; the norm is used.
// Generated by tools/gen_netz.py - edit the generator, not this file.
""", lane)
