# Generates Eternit lane 16 (Vulkan): cone with rimmed bowl and hole, and the chute leading up to it, as an OBJ + lane file.
import math, sys, os
from objgen import Mesh, sstep, cosramp, save_lane, lanes_dir

CX, CZ = 0.0, 5.55            # cone axis = centre of the target circle (norm drawing)
RB = 0.45                     # base radius of the cone (norm drawing: about 0.42; photos 0.40-0.45)
HT = 0.40                     # height of the rim (photo estimate, about knee height)
R_RIM, R_OUT = 0.165, 0.187   # crest of the bowl rim, outer edge of the rim
R_FLOOR = 0.125               # bowl floor radius
Y_FLOOR = HT - 0.042          # bowl floor at its outer edge
R_HOLE = 0.0546               # the game's hole radius
Y_HOLE = HT - 0.058           # edge of the hole
Y_CUP = Y_HOLE - 0.10         # bottom of the hole
ZF = 4.40                     # foot of the chute on the lane
ZB = CZ - R_FLOOR               # the chute floor reaches the bowl floor here

def cone(r):
    """outside surface of the cone and its rim (r >= R_RIM)"""
    if r >= RB: return 0.0
    if r >= R_OUT: return (HT - 0.015) * (RB - r) / (RB - R_OUT)
    return HT - 0.015 * cosramp((r - R_RIM) / (R_OUT - R_RIM))

def bowl(r):
    if r >= R_RIM: return cone(r)
    if r >= R_FLOOR: return Y_FLOOR + (HT - Y_FLOOR) * cosramp((r - R_FLOOR) / (R_RIM - R_FLOOR))
    if r >= 0.075: return Y_HOLE + 0.006 + (Y_FLOOR - Y_HOLE - 0.006) * (r - 0.075) / (R_FLOOR - 0.075)
    if r >= R_HOLE + 0.006: return Y_HOLE + 0.006
    return Y_HOLE

def chute(z):
    """half width of the channel floor, floor height, wall height"""
    s = min(1.0, max(0.0, (z - ZF) / (ZB - ZF)))
    wc = 0.165 - 0.0975 * sstep(s * 1.25)
    fc = Y_FLOOR * s ** 1.7 if z < ZB else bowl(CZ - z) - 0.0015
    wall = (0.03 * sstep(s / 0.2) + 0.03 * sstep((s - 0.2) / 0.5)) * sstep((CZ - 0.105 - z) / 0.04)   # 3 cm soon after the lip, 6 cm at the top
    return wc, fc, wall

def ground(x, z):
    return cone(math.hypot(x - CX, z - CZ)) if math.hypot(x - CX, z - CZ) >= R_RIM else HT

M = Mesh()
# ---- cone + bowl: surface of revolution; under the chute it is pushed below the chute floor
NPHI = 180
radii = [R_HOLE, R_HOLE + 0.006, R_HOLE + 0.0061, 0.075, 0.09, 0.105, 0.118, R_FLOOR] + \
        [R_FLOOR + (R_RIM - R_FLOOR) * k / 6 for k in range(1, 7)] + [R_RIM + (R_OUT - R_RIM) * k / 5 for k in range(1, 6)] + \
        [R_OUT + (RB - R_OUT) * k / 22 for k in range(1, 23)]
def lathe_ring(phi):
    c, s = math.cos(phi), math.sin(phi); out = []
    for r in radii:
        x, z = CX + r * c, CZ + r * s; y = bowl(r)
        if z < CZ and r > R_FLOOR - 0.002:
            wc, fc, wall = chute(z)
            if abs(x) < wc + 0.02: y = min(y, fc - 0.012)
        out.append((x, y, z))
    out.append((CX + (RB + 0.012) * c, -0.004, CZ + (RB + 0.012) * s))
    return out
M.skin([lathe_ring(2 * math.pi * k / NPHI) for k in range(NPHI)], 0, closed=True)
# hole: shaft and bottom (own vertices: crisp edge)
shaft = lambda phi: [(CX, Y_CUP, CZ), (CX + R_HOLE * math.cos(phi), Y_CUP, CZ + R_HOLE * math.sin(phi)), (CX + R_HOLE * math.cos(phi), Y_HOLE, CZ + R_HOLE * math.sin(phi))]
M.skin([shaft(2 * math.pi * k / 48) for k in range(48)], 1, closed=True)

# ---- chute: channel with low side walls, on its own skin that follows the channel edges
def chute_ring(z):
    wc, fc, wall = chute(z)
    edge = sstep((z - ZF) / 0.05)
    fc = fc * 1.0 - 0.004 * (1 - edge)
    crest = fc + wall
    half = []
    # from the outside in: skirt foot, skirt, crest (rounded), inner face, floor edge
    xo = wc + 0.024
    g = ground(xo + 0.03, z)
    sk = max(0.012, (crest - g) * 0.5)
    half.append((xo + sk + 0.01, min(g, crest) - 0.012))
    half.append((xo + sk * 0.5, (crest + min(g, crest)) / 2))
    k = min(1.0, wall / 0.01)
    half.append((xo, crest - 0.002 * k))
    half.append((wc + 0.016, crest))
    half.append((wc + 0.008, crest - 0.004 * k))
    for u in (0.75, 0.5, 0.25, 0.1): half.append((wc + 0.008 * u * u, fc + (crest - 0.004 * k - fc) * u * u))
    half.append((wc - 0.012, fc + 0.0005))
    half.append((wc * 0.5, fc));
    pts = [(-x, y, z) for x, y in half] + [(0.0, fc, z)] + [(x, y, z) for x, y in reversed(half)]
    return pts
NZ = 110
zs = [ZF + (ZB + 0.02 - ZF) * j / NZ for j in range(NZ + 1)]
M.skin([chute_ring(z) for z in zs], 2)

preview = len(sys.argv) > 1
M.write(sys.argv[1] if preview else os.path.join(lanes_dir(), 'eternit_16_vulkan.obj'), 'Vulkan - generated by tools/gen_vulkan.py')
